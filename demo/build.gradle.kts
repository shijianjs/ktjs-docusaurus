plugins {
    kotlin("multiplatform")
    id("io.github.shijianjs.ktjs.docusaurus")
}

/**
 * The demo is a documentation site, not a published module: its Markdown lives in
 * `src/jsMain/resources/{docs,pages,css,static}`, its configuration is Kotlin in `src/jsMain/kotlin`,
 * and `./gradlew :demo:docusaurusBuild` turns both into a static site.
 *
 * The landing-page elements and the TOC toggle live in `src/jsMain/kotlin/.../demo/client` and are
 * registered from `onRouteDidUpdate`. They are safe in this bundle because the element classes come
 * from a short JavaScript bridge rather than Kotlin classes — see `ElementRegistry.kt`.
 */
kotlin {
    js {
        useEsModules()

        // The configuration is loaded by Node when Docusaurus builds the site, so the target needs a
        // Node environment even though nothing is ever executed in a browser.
        nodejs()

        // A library binary: the plugin copies the linked module next to the site and the generated
        // `docusaurus.config.mjs` imports the exported configuration from it.
        binaries.library()
    }

    compilerOptions {
        optIn.add("kotlin.js.ExperimentalWasmJsInterop")
    }

    sourceSets {
        jsMain.dependencies {
            implementation(project(":ktjs-docusaurus"))
            implementation(project(":ktjs-docusaurus-kit"))
        }
    }
}

docusaurus {
    // `sidebars` is exported next to `docusaurusConfig`; leaving it out would generate a site with
    // autogenerated sidebars only.
    sidebarsFunction = "sidebars"

    // `onRouteDidUpdate` registers the landing-page elements and drives the TOC toggle. It runs after
    // hydration, so the custom elements never fight React over the same DOM.
    clientModuleFunction = "onRouteDidUpdate"
}
