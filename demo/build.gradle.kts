plugins {
    kotlin("multiplatform")
    id("io.github.shijianjs.ktjs.docusaurus")
}

/**
 * The demo is a documentation site, not a published module: its Markdown lives in
 * `src/jsMain/resources/docs`, its configuration is Kotlin in `src/jsMain/kotlin`, and
 * `./gradlew :demo:docusaurusBuild` turns both into a static site.
 *
 * This module holds the Node side (configuration, sidebars, the TOC client module). The landing page's
 * custom elements live in `:demo-client`, because a custom-element class reads `HTMLElement` when its
 * module loads and Node has none.
 */
kotlin {
    js {
        useEsModules()

        // The configuration is loaded by Node when Docusaurus builds the site, so the target needs a
        // Node environment even though nothing is ever executed in a browser.
        nodejs()

        // A library binary: the plugin copies the linked module next to the site and the generated
        // `docusaurus.config.mjs` imports the exported configuration from it.
        binaries.library()
    }

    compilerOptions {
        optIn.add("kotlin.js.ExperimentalWasmJsInterop")
    }

    sourceSets {
        jsMain.dependencies {
            implementation(project(":ktjs-docusaurus"))
        }
    }
}

docusaurus {
    // `sidebars` is exported next to `docusaurusConfig`; leaving it out would generate a site with
    // autogenerated sidebars only.
    sidebarsFunction = "sidebars"

    // The landing page's custom elements: published under `static/ktjs-client/` and loaded by a
    // `<script type="module">` tag (see `headTags` in the configuration), never by the server build.
    browserBundle = "ktjs-docusaurus-demo-client.mjs"
    browserBundleEntry = "start"
    additionalJs.from(
        project(":demo-client").layout.buildDirectory.dir("compileSync/js/main/productionLibrary/kotlin"),
    )
}

// A file collection cannot carry a task dependency across projects, so the link tasks the site copies
// from are wired in explicitly. The kit and the wrapper have to be linked before the site is
// assembled, otherwise the copied `.mjs` files are whatever the last build left behind.
tasks.named("docusaurusSite") {
    dependsOn(
        ":demo-client:jsProductionLibraryCompileSync",
        ":ktjs-docusaurus:jsProductionLibraryCompileSync",
        ":ktjs-docusaurus-kit:jsProductionLibraryCompileSync",
    )
}
