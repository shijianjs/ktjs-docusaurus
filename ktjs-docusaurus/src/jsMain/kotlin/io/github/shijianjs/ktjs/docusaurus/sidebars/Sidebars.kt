package io.github.shijianjs.ktjs.docusaurus.sidebars

import js.objects.Record
import kotlin.js.JsAny
import js.reflect.unsafeCast

/**
 * Upstream `SidebarsConfig`: the object a `sidebars.ts` exports.
 *
 * Every key is a sidebar id, referenced by `{type: "docSidebar", sidebarId: "..."}` in the navbar.
 * The keys are site-specific, so the record stays open:
 *
 * ```kotlin
 * val sidebars: SidebarsConfig = buildRecord {
 *     set("userGuide", arrayOf(/* items */))
 * }
 * ```
 *
 * @see <a href="https://docusaurus.io/docs/sidebar">Sidebar</a>
 */
typealias SidebarsConfig = Record<JsAny, Array<SidebarItem>>

/** Upstream `string`, narrowed to the built-in item kinds. */
sealed external interface SidebarItemType

/** Wraps a value coming from JavaScript. Prefer [SidebarItemTypes]. */
inline fun SidebarItemType(value: String): SidebarItemType = unsafeCast<SidebarItemType>(value)

/** The literals of [SidebarItemType]. */
object SidebarItemTypes {
    /** A document of this docs instance. */
    inline val doc: SidebarItemType get() = SidebarItemType("doc")

    /** A document of another docs instance. */
    inline val ref: SidebarItemType get() = SidebarItemType("ref")

    /** A collapsible group. */
    inline val category: SidebarItemType get() = SidebarItemType("category")

    /** An external link. */
    inline val link: SidebarItemType get() = SidebarItemType("link")

    /** A group generated from a directory's files. */
    inline val autogenerated: SidebarItemType get() = SidebarItemType("autogenerated")

    /** Raw markup. */
    inline val html: SidebarItemType get() = SidebarItemType("html")
}

/**
 * Upstream `SidebarItemDoc | SidebarItemCategory | SidebarItemLink | SidebarItemAutogenerated |
 * SidebarItemHtml`.
 *
 * Docusaurus declares one shape per item kind; they share this interface's fields and each kind
 * reads the ones it needs, which is how the upstream union behaves after validation.
 */
external interface SidebarItem {
    /** Item kind. */
    var type: SidebarItemType?

    /** `doc`: doc id, defaults to the file path without its extension. */
    var id: String?

    /** `ref`: the doc id this item points at. */
    var docId: String?

    /** Visible text. Falls back to the doc title. */
    var label: String?

    /** `link`: the external URL. */
    var href: String?

    /** `category`: the child items. */
    var items: Array<SidebarItem>?

    /** `category`: start collapsed. */
    var collapsed: Boolean?

    /** `category`: allow collapsing. */
    var collapsible: Boolean?

    /** `category`: make the label itself a link. */
    var link: SidebarCategoryLink?

    /** `autogenerated`: the directory, relative to the docs path. */
    var dirName: String?

    /** `html`: raw markup. */
    var value: String?

    /** `html`: the wrapper style, e.g. `'danger'`. */
    var defaultStyle: String?

    /** Extra class name for the item. */
    var className: String?

    /** Arbitrary data, readable from swizzled components. */
    var customProps: Record<JsAny, JsAny>?
}

/**
 * Upstream `SidebarItemCategoryLinkDoc | SidebarItemCategoryLinkGeneratedIndex`.
 *
 * A doc link turns the category label into a link to an existing doc; a generated index creates a
 * landing page for the category.
 */
external interface SidebarCategoryLink {
    /** `'doc'` or `'generated-index'`. */
    var type: SidebarCategoryLinkType?

    /** `doc`: the doc to link to. */
    var id: String?

    /** `generated-index`: URL segment of the generated page. */
    var slug: String?

    /** `generated-index`: page title. */
    var title: String?

    /** `generated-index`: meta description. */
    var description: String?

    /** `generated-index`: social card image. */
    var image: String?

    /** `generated-index`: keywords for the meta tag. */
    var keywords: Array<String>?
}

/** Upstream `'doc' | 'generated-index'`. */
sealed external interface SidebarCategoryLinkType

/** Wraps a value coming from JavaScript. Prefer [SidebarCategoryLinkTypes]. */
inline fun SidebarCategoryLinkType(value: String): SidebarCategoryLinkType = unsafeCast<SidebarCategoryLinkType>(value)

/** The literals of [SidebarCategoryLinkType]. */
object SidebarCategoryLinkTypes {
    /** Link the category label to a doc. */
    inline val doc: SidebarCategoryLinkType get() = SidebarCategoryLinkType("doc")

    /** Generate a landing page for the category. */
    inline val generatedIndex: SidebarCategoryLinkType
        get() = SidebarCategoryLinkType("generated-index")
}
