package io.github.shijianjs.docusaurus.sidebars

import js.objects.buildRecord
import js.objects.unsafeJso
import js.reflect.unsafeCast
import kotlin.js.JsAny
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Upstream source: `@docusaurus/plugin-content-docs` (`lib/sidebars/types.d.ts`) — `SidebarsConfig`
 * is a record of sidebar id to item array, and items are discriminated by `type`.
 */
class SidebarsTest {

    @Test
    fun sidebarRecordIsKeyedBySidebarId() {
        val sidebars: SidebarsConfig = buildRecord {
            set(
                "userGuide",
                arrayOf<SidebarItem>(
                    unsafeJso { type = SidebarItemTypes.doc; id = "intro" },
                ),
            )
        }

        val items = requireNotNull(sidebars.get(unsafeCast<JsAny>("userGuide")))

        assertEquals(1, items.size)
        assertEquals("doc", items[0].type.unsafeCast<String>())
        assertEquals("intro", items[0].id)
    }

    @Test
    fun itemTypes() {
        assertEquals("doc", SidebarItemTypes.doc.unsafeCast<String>())
        assertEquals("ref", SidebarItemTypes.ref.unsafeCast<String>())
        assertEquals("category", SidebarItemTypes.category.unsafeCast<String>())
        assertEquals("link", SidebarItemTypes.link.unsafeCast<String>())
        assertEquals("autogenerated", SidebarItemTypes.autogenerated.unsafeCast<String>())
        assertEquals("html", SidebarItemTypes.html.unsafeCast<String>())
    }

    @Test
    fun categoryLinkTypes() {
        assertEquals("doc", SidebarCategoryLinkTypes.doc.unsafeCast<String>())
        assertEquals("generated-index", SidebarCategoryLinkTypes.generatedIndex.unsafeCast<String>())
    }
}
